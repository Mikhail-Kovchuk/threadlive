import type { ReactNode } from 'react';

// --- What the API returns ----------------------------------------------------

/**
 * `context`: a card about what the conversation is about from here on, e.g.
 * "About invoice INV-1042" — written by the backend (ChatHost::contextLine)
 * from the page the visitor wrote on.
 */
export type MessageDirection = 'visitor' | 'agent' | 'system' | 'context';

/** A file on a message, behind a signed link. */
export interface ChatAttachment {
  id: string;
  name: string;
  mime: string;
  /** Bytes. */
  size: number;
  kind: 'image' | 'file';
  url: string;
}

/** A message as the backend returns it. Internal notes never reach the widget. */
export interface ChatMessage {
  id: number;
  direction: MessageDirection;
  body: string;
  /** ISO 8601. */
  created_at: string;
  /** The agent's name when the backend shows agent names, null otherwise. */
  author?: string | null;
  /** Echoed back for the visitor's own messages, so a retry is recognised. */
  client_msg_id?: string | null;
  attachments?: ChatAttachment[];
}

export interface AttachmentRules {
  enabled: boolean;
  /** Per file, in KB. */
  max_kb: number;
  /** Per message. */
  max_files: number;
  /** MIME types (or .ext) the file picker offers. */
  accept: string[];
}

export type ConversationStatus = 'waiting' | 'answered' | 'closed';

export interface ConversationState {
  status: ConversationStatus;
  /** Agent messages the visitor has not seen. */
  unread: number;
  /** Where offline replies also go, once the visitor has left it. */
  email?: string | null;
  /**
   * Live: not closed and recently active, so a reply may still come. Only a
   * live conversation is polled while the panel is closed.
   */
  active: boolean;
}

export interface SupportHours {
  /** "09:00" */
  from: string;
  /** "23:00" */
  to: string;
  /** IANA zone the hours are in, e.g. "Europe/Nicosia". */
  tz: string;
}

/** GET /bootstrap: everything the widget needs before it shows anything. */
export interface Bootstrap {
  /** False hides the widget entirely. */
  enabled: boolean;
  /** Within support hours. */
  online: boolean;
  hours: SupportHours;
  /** False for a guest when the backend does not take messages from guests. */
  can_write: boolean;
  /**
   * open: panel open. closed: panel closed, live conversation only. idle:
   * panel open but the visitor idle. idle_after: no input for this long is
   * idle — and stops polling altogether while the panel is closed.
   */
  poll_ms: { open: number; closed: number; idle: number; idle_after: number };
  /** Buttons on the first screen (config threadlive.topics); the `topics` prop overrides them. */
  topics: string[];
  max_message_length: number;
  /** The header's "go elsewhere" button (config threadlive.fallback); null for none. */
  fallback: { url: string; label: string | null } | null;
  attachments: AttachmentRules;
  /** Shown as "Maria · Support", or alone when agent names are hidden. */
  agent_display_name: string;
  /** This visitor's conversation, if there is one. */
  conversation: ConversationState | null;
}

/** Where the visitor wrote from; the backend's ChatHost turns it into card lines. */
export interface SendContext {
  url: string;
  title: string;
  /** What the page's `getContext` returned, e.g. `{ invoice: 'INV-1042' }`. */
  attributes: Record<string, unknown>;
}

export interface SendInput {
  body: string;
  /** Generated by the widget; the backend stores a retried send only once. */
  client_msg_id: string;
  context?: SendContext;
  /** Sent as multipart when there are any. */
  files?: File[];
}

export interface SendResult {
  message: ChatMessage;
  /**
   * The context card this send created, if any. It is stored before the
   * message (a lower id), so polling for what came after the message would
   * never return it.
   */
  context?: ChatMessage | null;
  conversation: ConversationState;
}

export interface MessagesResult {
  messages: ChatMessage[];
  /** Null when this visitor has no conversation (any more). */
  conversation: ConversationState | null;
}

/**
 * How the widget talks to the backend. `apiUrl` gets the HTTP one; pass your
 * own as `transport` to proxy, record, or preview without a backend
 * (`createDemoTransport()`).
 */
export interface ThreadliveTransport {
  bootstrap(): Promise<Bootstrap>;
  /** Messages after `after` (an id), or the whole history for null. */
  messages(after: number | null): Promise<MessagesResult>;
  send(input: SendInput): Promise<SendResult>;
  markRead(messageId: number): Promise<void>;
  saveEmail(email: string): Promise<void>;
}

// --- Props --------------------------------------------------------------------

interface CommonProps {
  /** Overrides of the theme's CSS variables. */
  theme?: ThreadliveTheme;
  /** Any of the widget's copy; English defaults for the rest. */
  texts?: Partial<ThreadliveTexts>;
  /** Corner of the screen. Default right. */
  position?: 'right' | 'left';
  /** Shown in the header's round badge; the title's initial otherwise. */
  logo?: ReactNode;
  /**
   * The button that opens the chat:
   * 'pill' (default) — icon and `texts.launcher`, round on phones;
   * 'icon' — round, icon only, everywhere;
   * 'none' — no button: put your own anywhere, open the chat with
   * `ref.current.open()`, and show the unread count from `onUnreadChange`.
   */
  launcher?: 'pill' | 'icon' | 'none';
  /** Your own icon in the launcher, instead of the chat bubble. */
  launcherIcon?: ReactNode;
  /**
   * When a reply arrives the visitor cannot see: "(1)" in the tab's title
   * while the tab is hidden, and a soft chime. Both on by default.
   */
  notify?: { title?: boolean; sound?: boolean };
  /** Agent names for the avatars on the first screen. */
  agents?: string[];
  /**
   * Buttons on the first screen; pressing one sends it as the first message.
   * Usually set on the server (config threadlive.topics) so that changing
   * them needs no frontend release; this overrides that list.
   */
  topics?: string[];
  /**
   * The header's link out of the widget, e.g. your Telegram support account.
   * Usually set on the server (config threadlive.fallback); this overrides it.
   */
  fallbackUrl?: string;
  /** Attributes of the page sent with each message, e.g. the code of the record on it. */
  getContext?: () => Record<string, unknown>;
  /** Called whenever the number of unread replies changes. */
  onUnreadChange?: (count: number) => void;
  /** Renders nothing while true, e.g. on pages where the chat does not belong. */
  hidden?: boolean;
}

interface HttpProps {
  /**
   * Where the Laravel package's routes are: your API origin plus the route
   * prefix, e.g. `https://api.example.com/threadlive`.
   */
  apiUrl: string;
  /** Headers for every request — where your own auth goes, e.g. a JWT. */
  getAuthHeaders?: () => Record<string, string> | Promise<Record<string, string>>;
  transport?: never;
}

interface TransportProps {
  transport: ThreadliveTransport;
  apiUrl?: never;
  getAuthHeaders?: never;
}

export type ThreadliveProps = CommonProps & (HttpProps | TransportProps);

/** What a ref to <Threadlive> can do. */
export interface ThreadliveHandle {
  open(): void;
  close(): void;
}

/**
 * Each value becomes a CSS variable on the widget's root element. Anything
 * left out keeps the default from `threadlive-react/styles.css`.
 */
export interface ThreadliveTheme {
  /** `--tl-accent`: buttons, the launcher, the visitor's messages. */
  accent?: string;
  /** `--tl-header-bg`: the panel's header. */
  headerBg?: string;
  /**
   * `--tl-font`. The widget loads no fonts of its own; pass the page's, e.g.
   * `var(--font-geist)` with `next/font`.
   */
  fontFamily?: string;
  /** `--tl-radius`: the panel's corners, e.g. `20px`. */
  radius?: string;
  /** `--tl-offset-x`: distance from the side of the screen, e.g. `24px`. */
  offsetX?: string;
  /** `--tl-offset-y`: distance from the bottom, e.g. `24px` — raise it to clear a cookie bar. */
  offsetY?: string;
}

