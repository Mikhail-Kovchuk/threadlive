// Writes src/version.ts from package.json, before every build, type check and
// test run.
//
// The version reaches the browser as a constant: a bundle cannot read
// package.json at run time. The release workflow sets package.json from the
// tag BEFORE building, so a published build names its release; a local one
// names whatever package.json says (0.0.0-dev in the repository).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

writeFileSync(
  join(root, 'src', 'version.ts'),
  `// Generated by scripts/write-version.mjs from package.json. Do not edit.\nexport const VERSION = ${JSON.stringify(version)};\n`,
);
